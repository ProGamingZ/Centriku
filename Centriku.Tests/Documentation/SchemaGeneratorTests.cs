using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using Xunit;
using Centriku.Models; 

namespace Centriku.Tests.Documentation
{
    public class SchemaGeneratorTests
    {
        [Fact]
        public void GenerateDatabaseSchemaMarkdown()
        {
            // 1. Locate the main Centriku/Models folder dynamically
            // AppContext.BaseDirectory points to Centriku.Tests/bin/Debug/net8.0/
            string projectRoot = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../centriku"));
            string modelsFolder = Path.Combine(projectRoot, "Models");
            string mdFilePath = Path.Combine(modelsFolder, "DatabaseSchema.md");

            // 2. Scan the compiled assembly for any class in the Models namespace
            // (We use 'Student' as a reference point to grab the right assembly)
            var modelTypes = typeof(Student).Assembly.GetTypes()
                .Where(t => t.IsClass && t.Namespace == "Centriku.Models" && !t.Name.Contains("<>"))
                .OrderBy(t => t.Name)
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("# Centriku Database Schema");
            sb.AppendLine("> *This file is automatically generated by `Centriku.Tests`. Do not edit it manually.*");
            sb.AppendLine($"> **Last Updated:** {DateTime.Now:MMMM dd, yyyy HH:mm:ss}\n");

            // 3. Build Markdown tables for each class
            foreach (var type in modelTypes)
            {
                sb.AppendLine($"## {type.Name}");
                sb.AppendLine("| Property | Type |");
                sb.AppendLine("|---|---|");

                var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance);
                foreach (var prop in properties)
                {
                    // Clean up type names for readability
                    string typeName = prop.PropertyType.Name;
                    
                    // Handle nullable types (e.g., int?, DateTime?)
                    if (Nullable.GetUnderlyingType(prop.PropertyType) != null)
                    {
                        typeName = Nullable.GetUnderlyingType(prop.PropertyType)!.Name + "?";
                    }

                    if (typeName == "String") typeName = "string";
                    else if (typeName == "Int32") typeName = "int";
                    else if (typeName == "Boolean") typeName = "bool";
                    else if (typeName == "Double") typeName = "double";

                    sb.AppendLine($"| **{prop.Name}** | `{typeName}` |");
                }
                sb.AppendLine();
            }

            // 4. Write the final markdown string to the file
            if (Directory.Exists(modelsFolder))
            {
                File.WriteAllText(mdFilePath, sb.ToString());
            }
        }
    }
}